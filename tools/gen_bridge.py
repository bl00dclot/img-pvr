"""Generate a pvrsrvkm bridge header (IDs + packed IN/OUT structs) from a DDK kernel tree.

Reads <km>/generated[/rogue]/<group>_bridge/common_<group>_bridge.h, keeps the kernel's declaration order and
emits the 32-bit-client-on-64-bit-kernel layout this winsys uses: every handle and pointer becomes uint64_t,
IMG_BOOL / enums become 32-bit. Unknown field types are an error, never a guess.

    tools/gen_bridge.py --km <kernel gpu_rgx/m1.13EDxxxx> --prefix ddk113 --source "<tree>@<sha>" > header.h

Self-check: run with --km <m1.11ED5425693> --prefix ddk111 and compare the struct bodies with the committed
pvr_srv_bridge_ddk111.h (`--compare`).
"""
import argparse
import os
import re
import sys

GROUPS = ["srvcore", "sync", "mm", "dmabuf", "rgxtq", "rgxcmp", "rgxta3d", "cache", "rgxhwperf"]

# (C type, size) per DDK type. Pointers and handles are handled separately (always uint64_t).
SCALARS = {
    "IMG_UINT8": ("uint8_t", 1), "IMG_UINT16": ("uint16_t", 2), "IMG_UINT32": ("uint32_t", 4),
    "IMG_UINT64": ("uint64_t", 8), "IMG_INT32": ("int32_t", 4), "IMG_INT64": ("int64_t", 8),
    "IMG_INT": ("int32_t", 4), "IMG_CHAR": ("char", 1), "IMG_BYTE": ("uint8_t", 1),
    "IMG_BOOL": ("uint32_t", 4), "PVRSRV_ERROR": ("uint32_t", 4), "IMG_PID": ("uint32_t", 4),
    "PDUMP_FLAGS_T": ("uint32_t", 4), "PVRSRV_CACHE_OP": ("uint32_t", 4),
    "PDUMP_POLL_OPERATOR": ("uint32_t", 4), "PVRSRV_FENCE": ("int32_t", 4),
    "PVRSRV_TIMELINE": ("int32_t", 4), "IMG_DEVMEM_SIZE_T": ("uint64_t", 8),
    "IMG_DEVMEM_OFFSET_T": ("uint64_t", 8), "IMG_DEVMEM_ALIGN_T": ("uint64_t", 8),
    "IMG_DEV_VIRTADDR": ("uint64_t", 8),
    # u32 unless the kernel is built with SUPPORT_VALIDATION (not in the MTK release configs).
    "PVRSRV_MEMALLOCFLAGS_T": ("uint32_t", 4),
}
# By-value structs, emitted as opaque byte arrays: name -> size (computed from the DDK header).
OPAQUE = {"RGX_HWPERF_BVNC": 160}  # char[24] + u32 + u16 + u16 + 16 x {u16 x 4}

ID_RE = re.compile(r"#define\s+PVRSRV_BRIDGE_([A-Z0-9]+)_([A-Z0-9_]+)\s+PVRSRV_BRIDGE_\1_CMD_FIRST\+(\d+)")
STRUCT_RE = re.compile(
    r"typedef struct PVRSRV_BRIDGE_(IN|OUT)_([A-Z0-9_]+)_TAG\s*\{(.*?)\}\s*__attribute__\s*\(\(packed\)\)", re.S)
FIELD_RE = re.compile(r"^(const\s+)?([A-Za-z0-9_]+)\s*(\*+)?\s*([A-Za-z0-9_]+)\s*(\[[^\]]*\])?;$")


def bridge_file(km, group):
    for sub in ("generated/rogue", "generated"):
        p = os.path.join(km, sub, f"{group}_bridge", f"common_{group}_bridge.h")
        if os.path.exists(p):
            return p
    sys.exit(f"error: no common_{group}_bridge.h under {km}")


def field(line, where):
    line = re.sub(r"/\*.*?\*/", "", line).strip()
    if not line:
        return None
    m = FIELD_RE.match(line)
    if not m:
        sys.exit(f"error: cannot parse field '{line}' in {where}")
    _, typ, ptr, name, arr = m.groups()
    if ptr or typ == "IMG_HANDLE":
        return f"uint64_t {name}; /* {typ}{' ' + ptr if ptr else ''} */", 8
    if arr:
        sys.exit(f"error: array field '{line}' in {where} (not supported, add explicitly)")
    if typ in OPAQUE:
        return f"uint8_t {name}[{OPAQUE[typ]}]; /* {typ} */", OPAQUE[typ]
    if typ not in SCALARS:
        sys.exit(f"error: unknown type {typ} in {where}")
    ctype, size = SCALARS[typ]
    return f"{ctype} {name};", size


def generate(km, prefix, source):
    out = [
        "/*",
        f" * Generated by tools/gen_bridge.py from the DDK services bridge headers of {source}",
        " * (generated/<group>_bridge/common_<group>_bridge.h, Copyright Imagination Technologies Ltd,",
        " * Dual MIT/GPLv2, used here under MIT). Do not edit.",
        " *",
        " * SPDX-License-Identifier: MIT",
        " */",
        "",
        f"#ifndef PVR_SRV_BRIDGE_{prefix.upper()}_H",
        f"#define PVR_SRV_BRIDGE_{prefix.upper()}_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    asserts = []
    for group in GROUPS:
        text = open(bridge_file(km, group)).read()
        out.append(f"/* ---- {group} ---- */")
        for g, fn, num in ID_RE.findall(text):
            out.append(f"#define {prefix.upper()}_BRIDGE_{g}_{fn} {num}U")
        out.append("")
        for direction, fn, body in STRUCT_RE.findall(text):
            name = f"{prefix}_{direction.lower()}_{fn.lower()}"
            fields = [f for f in (field(l, name) for l in body.split("\n")) if f]
            out.append(f"struct {name} {{")
            out.extend(f"   {decl}" for decl, _ in fields)
            out.append("} __attribute__((packed));")
            out.append("")
            asserts.append(f"_Static_assert(sizeof(struct {name}) == {sum(s for _, s in fields)}, \"{name}\");")
    out.append("/* Sizes as computed from the kernel headers: a compile error here means the packing changed. */")
    out.extend(asserts)
    out += ["", f"#endif /* PVR_SRV_BRIDGE_{prefix.upper()}_H */", ""]
    return "\n".join(out)


def struct_bodies(text):
    """struct name -> list of 'type name' (comments and spacing ignored), for --compare."""
    res = {}
    for name, body in re.findall(r"struct (\w+) \{(.*?)\} __attribute__\(\(packed\)\);", text, re.S):
        res[name] = [re.sub(r"/\*.*?\*/", "", l).strip() for l in body.strip().split("\n")]
    return res


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--km", required=True, help="kernel GPU driver dir, e.g. .../gpu_rgx/m1.13ED5776728")
    ap.add_argument("--prefix", required=True, help="identifier prefix, e.g. ddk113")
    ap.add_argument("--source", required=True, help="provenance string written into the header")
    ap.add_argument("--compare", help="existing header: report struct-body differences instead of printing")
    a = ap.parse_args()
    text = generate(a.km, a.prefix, a.source)
    if not a.compare:
        sys.stdout.write(text)
        return
    mine, theirs = struct_bodies(text), struct_bodies(open(a.compare).read())
    diffs = [n for n in theirs if n in mine and mine[n] != theirs[n]]
    missing = [n for n in theirs if n not in mine]
    print(f"compared {len(theirs)} structs: {len(theirs) - len(diffs) - len(missing)} identical, "
          f"{len(diffs)} differ, {len(missing)} missing from generator output")
    for n in diffs + missing:
        print(f"  {'DIFF' if n in diffs else 'MISSING'} {n}")
    sys.exit(1 if diffs or missing else 0)


if __name__ == "__main__":
    main()
