#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Regenerates tools/vktest/vkbench_spv.h from the shaders in this directory, using glslangValidator from the
# build image (docker/Dockerfile). Run from the repository root: tools/vktest/bench/gen.sh
set -euo pipefail
cd "$(dirname "$0")"
out=../vkbench_spv.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
   echo '// SPDX-License-Identifier: MIT'
   echo '// Generated by tools/vktest/bench/gen.sh from tools/vktest/bench/*.vert, *.frag; do not edit.'
   echo '#pragma once'
   echo '#include <stdint.h>'
} > "$tmp/out.h"
for f in *.vert *.frag; do
   n=spv_$(echo "$f" | tr . _)
   docker run --rm --network none --cap-drop ALL --user "$(id -u):$(id -g)" -v "$PWD:/in:ro" -v "$tmp:/out" \
      img-pvr-build:trixie glslangValidator -V --vn "$n" -o "/out/$n.h" "/in/$f" > /dev/null
   grep -v -e '^[[:space:]]*//' -e '#pragma once' -e '#include' "$tmp/$n.h" >> "$tmp/out.h"
done
mv "$tmp/out.h" "$out"
echo "wrote $out"
